#!/usr/bin/env bash
# Exercise admission and actual simulator outcomes with synthetic service costs.
set -euo pipefail
[[ $# == 1 ]] || { printf 'usage: %s SIMULATOR_EXECUTABLE\n' "$0" >&2; exit 2; }
scenario_simulator=$(realpath "$1")
[[ -x "$scenario_simulator" ]]
cd "$(git rev-parse --show-toplevel)"
scenario_scripts=$(realpath docs/experiments)
scenario_tmp=$(mktemp -d /tmp/dualpace-scenario-check.XXXXXX)
trap 'rm -rf -- "$scenario_tmp"' EXIT
gzip -dc "$scenario_scripts/2026-10-31-dualpace-gpu-costs.json.gz" |
    jq -f "$scenario_scripts/2026-10-31-dualpace-scenario-fixture.jq" > "$scenario_tmp/original.json"

write_inputs() {
    jq -c '.cpu[]' "$1" > "$scenario_tmp/cpu.jsonl"
    jq -c '.transfers[]' "$1" > "$scenario_tmp/transfers.jsonl"
    jq '.gpu' "$1" > "$scenario_tmp/gpu.json"
    jq '.capacity' "$1" > "$scenario_tmp/capacity.json"
}

build_scenarios() {
    bash "$scenario_scripts/2026-10-31-dualpace-build-scenarios.sh" \
        "$scenario_tmp/cpu.jsonl" "$scenario_tmp/transfers.jsonl" \
        "$scenario_tmp/gpu.json" "$scenario_tmp/capacity.json" "$1"
}

# The generated budget must equal its declared projection plus missing costs.
# Only down projection receives assistance; zero missing work adds no stages.
write_inputs "$scenario_tmp/original.json"
build_scenarios "$scenario_tmp/node0"
jq -e '(.scenarios | length) == 54 and (.scenarios | all(
  (.trace.profiles.token | map(.cpu.duration_ns) | add) == (.derived.cpu_projection_ns + .derived.cpu_missing_ns)
  and (.trace.profiles.token | map(.gpu.duration_ns) | add) == (.derived.gpu_projection_ns + .derived.gpu_missing_ns)
  and (.trace.profiles.token | map(select(.assist != null)) | length) == 36
  and (.trace.profiles.token | all(.assist == null or (.name | endswith("_down"))))
  and (.trace.profiles.token | length) == (if .derived.cpu_missing_ns == 0 and .derived.gpu_missing_ns == 0 then 108 else 144 end)
  and .trace.schema_version == 3 and .trace.has_copy_compute_overlap == false))' \
    "$scenario_tmp/node0/scenarios.json" > /dev/null
printf '%s\n' 'PASS: 54 inputs conserve both processor budgets and fixed routing'

# Every input must be accepted by the actual simulator in all three modes.
# The projection-only balanced fixture has independently calculated makespans.
scenario_count=0
while IFS= read -r scenario_name; do
    "$scenario_simulator" --trace "$scenario_tmp/node0/$scenario_name.json" --output "$scenario_tmp/result.jsonl"
    jq -se '.[-1].kind == "cooperative_simulation_complete" and .[-1].admitted_scenarios == 3
      and (all(.[] | select(.kind == "cooperative_simulation") | .result.intervals[]; .end_ns > .start_ns))' \
        "$scenario_tmp/result.jsonl" > /dev/null
    if [[ "$scenario_name" == node0-q8-cpu0-gpu0-balanced ]]; then
        jq -se '([.[] | select(.kind == "cooperative_simulation") | .result.elapsed_ns][0:2] == [172800,8640000])
          and (all(.[] | select(.kind == "cooperative_simulation"); .result.simulated_tokens == 16))' \
            "$scenario_tmp/result.jsonl" > /dev/null
    fi
    rm -- "$scenario_tmp/result.jsonl"
    scenario_count=$((scenario_count + 1))
done < <(jq -r '.scenarios[].name' "$scenario_tmp/node0/scenarios.json")
[[ "$scenario_count" == 54 ]]
printf '%s\n' 'PASS: all 162 scheduling modes admit; known 172800/8640000ns makespans match'

# Changing placement preserves the full grid and selects that node capacity.
jq '.cpu |= map(if .kind == "cpu_projection_manifest" then .placement.cpu=31 | .placement.numa_node=1 else . end) |
    .transfers |= map(if .kind == "cooperative_transfer_manifest" then .placement.cpu=31 | .placement.numa_node=1 else . end) |
    .capacity.nodes[1].capacity_bytes = 32000000000' "$scenario_tmp/original.json" > "$scenario_tmp/node1-input.json"
write_inputs "$scenario_tmp/node1-input.json"
build_scenarios "$scenario_tmp/node1"
jq -e '(.scenarios|length) == 54 and (.scenarios|all(.trace.cpu_numa_node == 1 and .trace.memory.host_capacity_bytes == 32000000000))' \
    "$scenario_tmp/node1/scenarios.json" > /dev/null
# Moving a generated bundle must preserve relative source evidence resolution.
mv "$scenario_tmp/node1" "$scenario_tmp/moved"
"$scenario_simulator" --trace "$scenario_tmp/moved/node1-q8-cpu0-gpu1-balanced.json" --output "$scenario_tmp/node1-result.jsonl"
jq -se '.[-1].admitted_scenarios == 3' "$scenario_tmp/node1-result.jsonl" > /dev/null
printf '%s\n' 'PASS: second NUMA placement and relocated artifact bundle'

# Refusing an existing output must preserve every previously generated byte.
if build_scenarios "$scenario_tmp/node0" > "$scenario_tmp/overwrite.log" 2>&1; then
    printf 'FAIL: existing output was accepted\n' >&2
    exit 1
fi
(cd "$scenario_tmp/node0" && sha256sum --check artifacts.sha256 > /dev/null)
printf '%s\n' 'PASS: existing output rejected and complete bundle unchanged'

expect_rejection() {
    local description=$1
    local mutation=$2
    jq "$mutation" "$scenario_tmp/original.json" > "$scenario_tmp/changed.json"
    write_inputs "$scenario_tmp/changed.json"
    if build_scenarios "$scenario_tmp/rejected" > "$scenario_tmp/rejected.log" 2>&1; then
        printf 'FAIL: accepted %s\n' "$description" >&2
        exit 1
    fi
    [[ ! -e "$scenario_tmp/rejected" ]]
    printf 'PASS: reject %s without output bundle\n' "$description"
}

# Completion and matching CPU placement are prerequisites for using measured costs.
expect_rejection 'incomplete CPU report' '.cpu |= map(select(.kind != "cpu_projection_complete"))'
expect_rejection 'validation-only report' '.cpu[0].is_validation_only = true'
expect_rejection 'mismatched NUMA placement' '.transfers[0].placement.numa_node = 1'
# Matching dimensions alone do not prove identical original weights or activations.
expect_rejection 'different input bytes' '.cpu |= map(if .kind == "cpu_projection_validation" then .case.input_sha256 = "changed" else . end)'
expect_rejection 'failed CPU arithmetic' '.cpu |= map(if .kind == "cpu_projection_validation" then .avx2.max_tolerance_ratio = 2 else . end)'
expect_rejection 'zero measured CPU cost' '.cpu |= map(if .kind == "cpu_projection_pair" then .avx2_ms = 0 else . end)'
expect_rejection 'missing CPU timing pair' '.cpu |= map(select(.kind != "cpu_projection_pair" or .pair != 4))'
# Failed or incomplete transfers cannot silently become a simulation assumption.
expect_rejection 'unstable transfer costs' '.transfers |= map(if .kind == "cooperative_transfer_costs" then .timing_error = "unstable" else . end)'
expect_rejection 'different transfer byte count' '.transfers |= map(if .kind == "cooperative_transfer_pair" then .observations[0].logical_transfer_bytes_per_operation = 1 else . end)'
expect_rejection 'failed transfer guards' '.transfers |= map(if .kind == "cooperative_transfer_validation" then .guards_unchanged = false else . end)'

# The simulator independently checks hashes after generation, before output opens.
printf '\n' >> "$scenario_tmp/node0/sources/cpu.jsonl"
if "$scenario_simulator" --trace "$scenario_tmp/node0/node0-q8-cpu0-gpu0-balanced.json" \
    --output "$scenario_tmp/tampered-result.jsonl" > "$scenario_tmp/tampered.log" 2>&1; then
    printf 'FAIL: modified source artifact accepted\n' >&2
    exit 1
fi
[[ ! -e "$scenario_tmp/tampered-result.jsonl" ]]
printf '%s\n' 'PASS: modified source artifact rejected before simulation output'
